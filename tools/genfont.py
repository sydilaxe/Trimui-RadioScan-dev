#!/usr/bin/env python3
"""Render printable ASCII from a monospace TTF into a 1-bit C header (src/font.h).
Usage: genfont.py <font.ttf> <out.h>   (default: DejaVu Sans Mono)"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
out = sys.argv[2] if len(sys.argv) > 2 else "src/font.h"
W, H, SIZE = 10, 18, 15
font = ImageFont.truetype(ttf, SIZE)
asc, _ = font.getmetrics()
rows = []
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    bbox = font.getbbox(chr(c))
    x = (W - (font.getlength(chr(c)))) / 2
    d.text((x, -2), chr(c), fill=255, font=font)  # glyph boxes span y 3..18 at size 15
    bits = []
    for y in range(H):
        v = 0
        for xx in range(W):
            if img.getpixel((xx, y)) > 110:
                v |= 1 << (15 - xx)
        bits.append(v)
    rows.append(bits)
with open(out, "w") as f:
    f.write("/* Generated by tools/genfont.py from DejaVu Sans Mono Bold (Bitstream Vera license). */\n")
    f.write("#ifndef RS_FONT_H\n#define RS_FONT_H\n#include <stdint.h>\n")
    f.write(f"#define FONT_W {W}\n#define FONT_H {H}\n#define FONT_FIRST 32\n#define FONT_LAST 126\n")
    f.write(f"static const uint16_t font_bits[{len(rows)}][{H}] = {{\n")
    for c, bits in zip(range(32, 127), rows):
        f.write("  {" + ",".join(f"0x{b:04x}" for b in bits) + "}, /* " + (chr(c) if chr(c) not in "\\*/" else " ") + " */\n")
    f.write("};\n#endif\n")
